def visit(url,selector='body'):
    goto_url(url);wait_for_load();cdp('Page.bringToFront')
    until(lambda:ev('Boolean(document.querySelector('+json.dumps(selector)+'))'))
def api_call(path,method='GET',body=None):
    return ev("(async()=>{const s=await (await fetch('/api/session')).json();const r=await fetch("+json.dumps(path)+",{method:"+json.dumps(method)+",headers:{'Content-Type':'application/json','X-CSRF-Token':s.csrfToken},body:"+("undefined" if body is None else json.dumps(json.dumps(body)))+"});return {status:r.status,data:await r.json()}})()")
