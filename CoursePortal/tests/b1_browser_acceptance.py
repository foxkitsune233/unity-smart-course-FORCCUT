def fill_path(path,value):
    # Repeated chapter fields share accessible names. Use their observed data-path to identify the input.
    node=ev('document.querySelector('+json.dumps('[data-path="'+path+'"]')+').outerHTML')
    assert node, path
    box=ev('(()=>{const n=document.querySelector('+json.dumps('[data-path="'+path+'"]')+');n.scrollIntoView({block:"center"});const r=n.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()')
    click_at_xy(box['x'],box['y'])
    cdp('Input.dispatchKeyEvent',type='keyDown',key='a',code='KeyA',modifiers=2,windowsVirtualKeyCode=65,commands=['selectAll'])
    cdp('Input.dispatchKeyEvent',type='keyUp',key='a',code='KeyA',modifiers=2,windowsVirtualKeyCode=65)
    cdp('Input.insertText',text=str(value))
