"""Real Unity2021 first-two-experiment acceptance; run through browser-harness on QA8091."""
from pathlib import Path
exec(Path(r'D:\unity\CoursePortal\tests\b1_browser_acceptance.py').read_text(encoding='utf-8').split('\ntry:\n')[0])

def lab(n):
    visit(BASE+'lab/?lab='+n,'#unity-canvas')
    until(lambda:ev('Boolean(window.unityLab?.ready)'),60)
    until(lambda:ev('window.unityLab.state?.scene?.experimentId==='+json.dumps(n)),12)
def cmd(action,data=None):
    ev('window.unityLab.command('+json.dumps(action)+','+json.dumps(data or {})+')')
    time.sleep(.25)
def state():return ev('window.unityLab.state')

def key(code,key,duration):
    cdp('Input.dispatchKeyEvent',type='keyDown',key=key,code=code,windowsVirtualKeyCode=ord(key.upper()))
    time.sleep(duration)
    cdp('Input.dispatchKeyEvent',type='keyUp',key=key,code=code,windowsVirtualKeyCode=ord(key.upper()))
try:
    lab('lab01')
    check('LAB01_default_template_valid',state()['scene']['experimentId']=='lab01' and not state()['errors'])
    before=state()['scene'];key01=ev('window.unityLab.storageKey')
    click('▶ 运行','button')
    until(lambda:state()['mode']=='play')
    key('KeyD','d',2.3)
    until(lambda:state()['completed'],8)
    check('LAB01_real_keyboard_collects_3_coins_and_finishes',state()['score']==3 and state()['completed'],state()['score'])
    shot('labs12-ch01-play.png')
    click('■ 停止','button')
    until(lambda:state()['mode']=='edit')
    check('LAB01_Stop_restores_edit_objects',state()['scene']==before)
    cmd('attach',{'id':'ground','behavior':'playerMove'})
    check('script_attaches_to_floor_before_validation','playerMove' in next(o for o in state()['scene']['objects'] if o['id']=='ground')['scripts'])
    blocked_elapsed=state()['elapsed']
    click('▶ 运行','button');time.sleep(.4)
    check('missing_Rigidbody_blocks_whole_scene',state()['mode']=='edit' and any(x['id']=='ground' and x['field']=='rigidbody' for x in state()['errors']) and state()['elapsed']==blocked_elapsed)
    cmd('save');time.sleep(.3)
    cdp('Page.reload',ignoreCache=True);wait_for_load();until(lambda:ev('Boolean(window.unityLab?.ready)'),60)
    until(lambda:state()['scene']['experimentId']=='lab01')
    check('invalid_draft_roundtrip_retains_errors',any(x['id']=='ground' and x['field']=='rigidbody' for x in state()['errors']))
    cmd('removeScript',{'id':'ground','behavior':'playerMove'})
    cmd('save')
    lab('lab02')
    check('LAB02_separate_draft_key',ev('window.unityLab.storageKey')!=key01)
    check('LAB02_default_valid',not state()['errors'])
    before2=state()['scene']
    click('▶ 运行','button')
    until(lambda:state()['hits']>=3,16)
    check('LAB02_real_projectiles_hit_and_complete',state()['completed'] and state()['spawned']>=3)
    check('LAB02_lifecycle_callbacks_observed',state()['lifecycleStart']>0 and state()['lifecycleUpdate']>0 and state()['lifecycleFixed']>0)
    shot('labs12-ch02-play.png')
    click('■ 停止','button');until(lambda:state()['mode']=='edit')
    check('LAB02_Stop_removes_clones_restores_snapshot',state()['scene']==before2 and state()['alive']==0)
    emitter=next(o for o in state()['scene']['objects'] if 'spawnEmitter' in o['scripts'])
    settings=emitter['settings'].copy();settings['projectile']=''
    cmd('configure',{'id':emitter['id'],'settings':settings})
    click('▶ 运行','button');time.sleep(.3)
    check('LAB02_missing_reference_blocks_run',state()['mode']=='edit' and any(e['field']=='projectile' for e in state()['errors']))
    cmd('configure',{'id':emitter['id'],'settings':emitter['settings']})
    click('▶ 运行','button');until(lambda:state()['hits']>0,12)
    check('LAB02_repaired_reference_runs',state()['mode']=='play')
    click('■ 停止','button');cmd('save')
    cdp('Page.reload',ignoreCache=True);wait_for_load();until(lambda:ev('Boolean(window.unityLab?.ready)'),60)
    until(lambda:state()['scene']['experimentId']=='lab02')
    check('LAB02_save_reload_preserves_reference',next(o for o in state()['scene']['objects'] if o['id']==emitter['id'])['settings']['projectile']==emitter['settings']['projectile'])
    lab('lab01')
    check('return_LAB01_preserves_distinct_scene',state()['scene']['experimentId']=='lab01' and len(state()['scene']['objects'])==7 and not state()['errors'])
    shot('labs12-ch01-editor.png')
finally:
    EVIDENCE.joinpath('labs12-browser.json').write_text(json.dumps(results,ensure_ascii=False,indent=2),encoding='utf-8')
